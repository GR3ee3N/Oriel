// Cover startup with the mark, status and activity bar until Home is ready,
// then fade out. Connection and sign-in errors use the same screen with retry controls.

import { createEffect, createSignal, on, onCleanup, Show } from 'solid-js';
import { homeReady } from '../boot';
import { t } from '../i18n';
import { focusable } from '../nav';
import { root } from '../router';
import { chooseServer, retry, serverOptions, session } from '../session';
import { Backdrop } from './components/Backdrop';
import { Menu } from './components/Menu';
// Inline the mark so the first page frame matches Kodi's startup image.
import markSvg from './mark.svg?raw';
import './splash.css';

/** Arched window mark generated by tools/make-art.py. */
export function Mark(props: { size: number }) {
  return (
    <span
      class="mark"
      style={{ width: `${props.size}px`, height: `${props.size}px` }}
      aria-hidden="true"
      innerHTML={markSvg}
    />
  );
}

// Reveal Home after this timeout even if artwork or server responses are delayed.
const WAIT_FOR_HOME = 5000;

export function Splash() {
  const [timedOut, setTimedOut] = createSignal(false);
  let timer: ReturnType<typeof setTimeout> | undefined;
  createEffect(
    on(
      () => session.phase,
      (phase) => {
        clearTimeout(timer);
        setTimedOut(false);
        if (phase === 'ready') timer = setTimeout(() => setTimedOut(true), WAIT_FOR_HOME);
      },
    ),
  );
  onCleanup(() => clearTimeout(timer));

  const wanted = () => {
    const phase = session.phase;
    if (phase === 'loading' || phase === 'connecting' || phase === 'error') return true;
    return phase === 'ready' && root().route.screen === 'home' && !homeReady() && !timedOut();
  };
  // Keep the splash mounted until its fade finishes.
  const [mounted, setMounted] = createSignal(wanted());
  const [leaving, setLeaving] = createSignal(false);
  let fade: ReturnType<typeof setTimeout> | undefined;
  createEffect(
    on(wanted, (want) => {
      clearTimeout(fade);
      if (want) {
        setLeaving(false);
        setMounted(true);
      } else if (mounted()) {
        setLeaving(true);
        fade = setTimeout(() => setMounted(false), 500);
      }
    }),
  );
  onCleanup(() => clearTimeout(fade));

  const status = () => {
    switch (session.phase) {
      case 'connecting':
        return session.connectingTo ? t('start.connecting', { server: session.connectingTo }) : t('start.connectingAny');
      case 'ready':
        return t('start.loading');
      default:
        return t('start.starting');
    }
  };

  const [choosing, setChoosing] = createSignal(false);

  return (
    <Show when={mounted()}>
      <div class="splash" classList={{ leaving: leaving() }}>
        <Backdrop />
        <div class="splash-body">
          <Mark size={168} />
          <h1 class="wordmark">Oriel</h1>
          <Show
            when={session.phase === 'error'}
            fallback={
              <>
                <Show when={session.user && session.phase !== 'loading'}>
                  <div class="welcome">
                    {/* Keep the initial visible beneath the loading avatar. */}
                    <span class="avatar">
                      {session.user?.title?.[0]}
                      <Show when={session.user?.thumb}>{(src) => <img src={src()} alt="" />}</Show>
                    </span>
                    <span>{t('start.welcome', { user: session.user?.title ?? '' })}</span>
                  </div>
                </Show>
                <p class="splash-status">{status()}</p>
                <div class="splash-bar">
                  <div />
                </div>
              </>
            }
          >
            <h2>{t('start.failed')}</h2>
            <p class="splash-error">{session.error}</p>
            <div class="splash-buttons">
              <div class="btn" ref={(el) => focusable(el, { autofocus: true, onSelect: () => void retry() })}>{t('action.retry')}</div>
              <Show when={session.servers.length > 1}>
                <div class="btn" ref={(el) => focusable(el, { onSelect: () => setChoosing(true) })}>{t('start.chooseServer')}</div>
              </Show>
            </div>
          </Show>
        </div>
        <Show when={choosing()}>
          <Menu
            title="Server"
            options={serverOptions()}
            selected={session.serverId}
            onChoose={(id) => void chooseServer(id)}
            onClose={() => setChoosing(false)}
          />
        </Show>
      </div>
    </Show>
  );
}
